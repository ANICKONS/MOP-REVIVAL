        private static TypeKind DecideKind(StubType t, OverlayInfo overlay)
        {
            if (overlay.DeclaredKinds.TryGetValue(t.Name, out TypeKind k)) return k;
            bool isDelegate = t.Members.Values.Any(m => m.Kind == MemberKind.Ctor && m.Params.Count == 2
                && m.Params[0].Render() == "object" && m.Params[1].Render() == "global::System.IntPtr");
            if (isDelegate) return TypeKind.Delegate;
            if (t.SeenValueType && !t.IsInheritedLocally)
                return t.Members.Count == 0 ? TypeKind.Enum : TypeKind.Struct;
            return TypeKind.Class;
        }

        private void EmitType(StringBuilder sb, StubType t, OverlayInfo overlay, int depth)
        {
            string ind = new string(' ', depth * 4);
            TypeKind kind = DecideKind(t, overlay);
            t.Kind = kind;
            string generic = t.Arity > 0 ? "<" + string.Join(", ", Enumerable.Range(0, t.Arity).Select(i => "T" + i)) + ">" : "";
            string name = Escape(t.Name);

            // Enums/delegates declared in the overlay cannot be partial: the overlay owns them fully.
            if (overlay.DeclaredKinds.TryGetValue(t.Name, out TypeKind ok) && (ok == TypeKind.Enum || ok == TypeKind.Delegate))
                return;

            switch (kind)
            {
                case TypeKind.Enum:
                    sb.AppendLine($"{ind}public enum {name} {{ }}");
                    return;
                case TypeKind.Delegate:
                    StubMember invoke = t.Members.Values.FirstOrDefault(m => m.Name == "Invoke" && !m.IsStatic);
                    string ret = invoke != null ? invoke.Return.Render() : "void";
                    string pars = invoke != null ? RenderParams(invoke.Params, false) : "";
                    sb.AppendLine($"{ind}public delegate {ret} {name}{generic}({pars});");
                    return;
            }

            string keyword = kind == TypeKind.Struct ? "struct" : kind == TypeKind.Interface ? "interface" : "class";
            sb.AppendLine($"{ind}public partial {keyword} {name}{generic}");
            sb.AppendLine($"{ind}{{");

            bool isInterface = kind == TypeKind.Interface;
            string mInd = ind + "    ";

            // Fields
            foreach (StubMember f in t.Members.Values.Where(m => m.Kind == MemberKind.Field).OrderBy(m => m.Name, StringComparer.Ordinal))
            {
                if (overlay.SkippedMembers.Contains(t.Name + "." + f.Name)) continue;
                sb.AppendLine($"{mInd}public {(f.IsStatic ? "static " : "")}{f.Return.Render()} {Escape(f.Name)};");
            }

            // Constructors
            foreach (StubMember c in t.Members.Values.Where(m => m.Kind == MemberKind.Ctor && !m.IsStatic))
            {
                if (isInterface) continue;
                if (kind == TypeKind.Struct && c.Params.Count == 0) continue;
                if (overlay.SkippedMembers.Contains(t.Name + ".ctor" + c.Params.Count)) continue;
                sb.AppendLine($"{mInd}public {name}({RenderParams(c.Params, true)}) {{ throw null; }}");
            }

            List<StubMember> methods = t.Members.Values.Where(m => m.Kind == MemberKind.Method).ToList();

            // Properties (get_/set_), indexers and events.
            Dictionary<string, (StubMember get, StubMember set)> props = new Dictionary<string, (StubMember, StubMember)>();
            HashSet<StubMember> consumed = new HashSet<StubMember>();
            foreach (StubMember m in methods)
            {
                bool isGet = m.Name.StartsWith("get_") && m.GenericArity == 0 && m.Return.Render() != "void";
                bool isSet = m.Name.StartsWith("set_") && m.GenericArity == 0 && m.Params.Count >= 1 && m.Return.Render() == "void";
                if (!isGet && !isSet) continue;
                string pname = m.Name.Substring(4);
                List<TypeSig> index = isGet ? m.Params : m.Params.Take(m.Params.Count - 1).ToList();
                string key = pname + (m.IsStatic ? ":s" : ":i") + "(" + string.Join(",", index.Select(i => i.Render())) + ")";
                props.TryGetValue(key, out var pair);
                if (isGet) pair.get = m; else pair.set = m;
                props[key] = pair;
                consumed.Add(m);
            }

            foreach (var kv in props.OrderBy(k => k.Key, StringComparer.Ordinal))
            {
                StubMember g = kv.Value.get, s = kv.Value.set;
                StubMember any = g ?? s;
                string pname = any.Name.Substring(4);
                if (overlay.SkippedMembers.Contains(t.Name + "." + pname)) continue;

                TypeSig ptype = g != null ? g.Return : s.Params[s.Params.Count - 1];
                List<TypeSig> index = g != null ? g.Params : s.Params.Take(s.Params.Count - 1).ToList();
                bool isStatic = any.IsStatic;
                bool isVirtual = (g?.IsVirtual ?? false) || (s?.IsVirtual ?? false);
                string mods = isInterface ? "" : "public " + (isStatic ? "static " : isVirtual ? "virtual " : "");
                string decl = index.Count > 0 && pname == "Item"
                    ? $"{mods}{ptype.Render()} this[{RenderParams(index, false)}]"
                    : $"{mods}{ptype.Render()} {Escape(pname)}";
                if (index.Count > 0 && pname != "Item")
                {
                    // Non-default indexed property (not expressible in C#): emit as methods.
                    if (g != null) consumed.Remove(g);
                    if (s != null) consumed.Remove(s);
                    continue;
                }

                string accessors = isInterface
                    ? (g != null ? "get; " : "") + (s != null ? "set; " : "")
                    : (g != null ? "get { throw null; } " : "") + (s != null ? "set { } " : "");
                sb.AppendLine($"{mInd}{decl} {{ {accessors}}}");
            }

            foreach (StubMember m in methods.Where(m => m.Name.StartsWith("add_") || m.Name.StartsWith("remove_")))
            {
                consumed.Add(m);
            }
            foreach (var ev in methods.Where(m => m.Name.StartsWith("add_") && m.Params.Count == 1).GroupBy(m => m.Name.Substring(4)))
            {
                StubMember a = ev.First();
                if (overlay.SkippedMembers.Contains(t.Name + "." + ev.Key)) continue;
                string mods = isInterface ? "" : "public " + (a.IsStatic ? "static " : "");
                sb.AppendLine($"{mInd}{mods}event {a.Params[0].Render()} {Escape(ev.Key)};");
            }

            // Operators
            List<StubMember> ops = methods.Where(m => m.Name.StartsWith("op_") && m.IsStatic).ToList();
            foreach (StubMember m in ops) consumed.Add(m);
            if (!isInterface)
                EmitOperators(sb, mInd, t, ops, overlay);

            // Plain methods
            foreach (StubMember m in methods.Where(m => !consumed.Contains(m)).OrderBy(m => m.Name, StringComparer.Ordinal))
            {
                if (m.Name == ".cctor") continue;
                if (overlay.SkippedMembers.Contains(t.Name + "." + m.Name)) continue;
                string mg = m.GenericArity > 0 ? "<" + string.Join(", ", Enumerable.Range(0, m.GenericArity).Select(i => "M" + i)) + ">" : "";
                string mods = isInterface ? "" : "public " + (m.IsStatic ? "static " : m.IsVirtual ? "virtual " : "");
                string body = isInterface ? ";" : " { throw null; }";
                sb.AppendLine($"{mInd}{mods}{m.Return.Render()} {Escape(m.Name)}{mg}({RenderParams(m.Params, false)}){body}");
            }

            // Nested types
            foreach (StubType n in t.Nested.OrderBy(n => n.Name, StringComparer.Ordinal))
                EmitType(sb, n, overlay, depth + 1);

            sb.AppendLine($"{ind}}}");
        }

        private static readonly Dictionary<string, string> BinaryOps = new Dictionary<string, string>
        {
            ["op_Equality"] = "==", ["op_Inequality"] = "!=", ["op_Addition"] = "+", ["op_Subtraction"] = "-",
            ["op_Multiply"] = "*", ["op_Division"] = "/", ["op_Modulus"] = "%", ["op_LessThan"] = "<",
            ["op_GreaterThan"] = ">", ["op_LessThanOrEqual"] = "<=", ["op_GreaterThanOrEqual"] = ">=",
            ["op_BitwiseAnd"] = "&", ["op_BitwiseOr"] = "|", ["op_ExclusiveOr"] = "^"
        };

        private static readonly Dictionary<string, string> UnaryOps = new Dictionary<string, string>
        {
            ["op_UnaryNegation"] = "-", ["op_UnaryPlus"] = "+", ["op_LogicalNot"] = "!", ["op_OnesComplement"] = "~"
        };

        private static readonly Dictionary<string, string> PairOf = new Dictionary<string, string>
        {
            ["op_Equality"] = "op_Inequality", ["op_Inequality"] = "op_Equality",
            ["op_LessThan"] = "op_GreaterThan", ["op_GreaterThan"] = "op_LessThan",
            ["op_LessThanOrEqual"] = "op_GreaterThanOrEqual", ["op_GreaterThanOrEqual"] = "op_LessThanOrEqual"
        };

        private void EmitOperators(StringBuilder sb, string ind, StubType t, List<StubMember> ops, OverlayInfo overlay)
        {
            HashSet<string> emitted = new HashSet<string>();
            List<StubMember> all = new List<StubMember>(ops);

            // C# requires paired comparison operators.
            foreach (StubMember m in ops)
            {
                if (!PairOf.TryGetValue(m.Name, out string pair)) continue;
                bool hasPair = ops.Any(o => o.Name == pair && RenderParams(o.Params, false) == RenderParams(m.Params, false));
                if (!hasPair)
                    all.Add(new StubMember { Kind = MemberKind.Method, Name = pair, IsStatic = true, Return = m.Return, Params = m.Params });
            }

            foreach (StubMember m in all)
            {
                if (overlay.SkippedMembers.Contains(t.Name + "." + m.Name)) continue;
                string pars = RenderParams(m.Params, false);
                string key = m.Name + "(" + pars + ")" + m.Return.Render();
                if (!emitted.Add(key)) continue;

                if (m.Name == "op_Implicit" || m.Name == "op_Explicit")
                {
                    string kw = m.Name == "op_Implicit" ? "implicit" : "explicit";
                    sb.AppendLine($"{ind}public static {kw} operator {m.Return.Render()}({pars}) {{ throw null; }}");
                }
                else if (BinaryOps.TryGetValue(m.Name, out string bop) && m.Params.Count == 2)
                {
                    sb.AppendLine($"{ind}public static {m.Return.Render()} operator {bop}({pars}) {{ throw null; }}");
                }
                else if (UnaryOps.TryGetValue(m.Name, out string uop) && m.Params.Count == 1)
                {
                    sb.AppendLine($"{ind}public static {m.Return.Render()} operator {uop}({pars}) {{ throw null; }}");
                }
            }
        }

        private static string RenderParams(List<TypeSig> ps, bool isCtor)
        {
            List<string> parts = new List<string>();
            for (int i = 0; i < ps.Count; i++)
            {
                TypeSig p = ps[i];
                string prefix = p.IsByRef ? "out " : "";
                parts.Add(prefix + p.Render() + " p" + i);
            }
            return string.Join(", ", parts);
        }
