using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace RefStubGen
{
    internal sealed partial class Program
    {
        private sealed class OverlayInfo
        {
            public readonly Dictionary<string, TypeKind> DeclaredKinds = new Dictionary<string, TypeKind>();
            public readonly HashSet<string> SkippedMembers = new HashSet<string>();   // "Type.Member"
            public readonly HashSet<string> ExtraDependencies = new HashSet<string>();
        }

        private static readonly Regex TypeDeclRegex =
            new Regex(@"\b(?<kind>enum|interface|struct|class|delegate)\s+(?:[\w\.<>\[\],\s]+?\s+)?(?<name>[A-Za-z_]\w*)\s*(?:<[^>]*>)?\s*(?:[:{(]|where|$)", RegexOptions.Multiline);
        private static readonly Regex SkipRegex = new Regex(@"//\s*stub-skip:\s*(?<id>[\w\.]+)");
        private static readonly Regex DependsRegex = new Regex(@"//\s*stub-depends:\s*(?<asm>[\w\.\-]+)");

        private OverlayInfo ReadOverlay(string overlayDir, string assembly)
        {
            OverlayInfo info = new OverlayInfo();
            if (overlayDir == null) return info;
            string file = Path.Combine(overlayDir, assembly + ".cs");
            if (!File.Exists(file)) return info;

            string text = File.ReadAllText(file);
            foreach (Match m in TypeDeclRegex.Matches(text))
            {
                string kind = m.Groups["kind"].Value;
                string name = m.Groups["name"].Value;
                TypeKind k = kind switch
                {
                    "enum" => TypeKind.Enum,
                    "interface" => TypeKind.Interface,
                    "struct" => TypeKind.Struct,
                    "delegate" => TypeKind.Delegate,
                    _ => TypeKind.Class
                };
                if (!info.DeclaredKinds.ContainsKey(name))
                    info.DeclaredKinds[name] = k;
            }
            foreach (Match m in SkipRegex.Matches(text))
                info.SkippedMembers.Add(m.Groups["id"].Value);
            foreach (Match m in DependsRegex.Matches(text))
                info.ExtraDependencies.Add(m.Groups["asm"].Value);
            return info;
        }

        private void Emit(string outDir, string overlayDir)
        {
            Directory.CreateDirectory(outDir);
            string absOverlay = overlayDir != null ? Path.GetFullPath(overlayDir) : null;

            // Every target assembly gets a project, even if nothing was harvested (overlay-only).
            List<string> assemblies = targets.OrderBy(a => a, StringComparer.Ordinal).ToList();
            Dictionary<string, OverlayInfo> overlays = assemblies.ToDictionary(a => a, a => ReadOverlay(absOverlay, a));

            foreach (string asm in assemblies)
            {
                foreach (string dep in overlays[asm].ExtraDependencies)
                {
                    if (!dependencies.TryGetValue(asm, out HashSet<string> set))
                        dependencies[asm] = set = new HashSet<string>();
                    if (dep != asm) set.Add(dep);
                }
            }

            foreach (string asm in assemblies)
            {
                OverlayInfo overlay = overlays[asm];
                string projDir = Path.Combine(outDir, asm);
                Directory.CreateDirectory(projDir);

                StringBuilder sb = new StringBuilder();
                sb.AppendLine("// <auto-generated> RefStubGen: compile-only API stubs. Do not edit; use refs/overlay instead. </auto-generated>");
                sb.AppendLine("#pragma warning disable");
                Version v = versions.TryGetValue(asm, out Version found) ? found : new Version(0, 0, 0, 0);
                sb.AppendLine($"[assembly: global::System.Reflection.AssemblyVersion(\"{v}\")]");
                sb.AppendLine();

                IEnumerable<IGrouping<string, StubType>> byNamespace = types.Values
                    .Where(t => t.Assembly == asm && t.Declaring == null)
                    .GroupBy(t => t.Namespace ?? "")
                    .OrderBy(g => g.Key, StringComparer.Ordinal);

                int typeCount = 0;
                foreach (IGrouping<string, StubType> ns in byNamespace)
                {
                    bool hasNs = ns.Key.Length > 0;
                    if (hasNs) sb.AppendLine("namespace " + ns.Key).AppendLine("{");
                    foreach (StubType t in ns.OrderBy(t => t.Name, StringComparer.Ordinal))
                    {
                        EmitType(sb, t, overlay, hasNs ? 1 : 0);
                        typeCount++;
                    }
                    if (hasNs) sb.AppendLine("}");
                }

                File.WriteAllText(Path.Combine(projDir, asm + ".g.cs"), sb.ToString());
                File.WriteAllText(Path.Combine(projDir, asm + ".csproj"), BuildProject(asm, absOverlay));
                Console.WriteLine($"[RefStubGen] {asm}: {typeCount} top-level types, version {v}");
            }

            // Topological build order.
            List<string> order = new List<string>();
            HashSet<string> visiting = new HashSet<string>(), done = new HashSet<string>();
            void Visit(string a)
            {
                if (done.Contains(a)) return;
                if (!visiting.Add(a)) { Console.Error.WriteLine("[RefStubGen] warn: dependency cycle at " + a); return; }
                if (dependencies.TryGetValue(a, out HashSet<string> deps))
                    foreach (string d in deps.Where(targets.Contains).OrderBy(x => x, StringComparer.Ordinal)) Visit(d);
                visiting.Remove(a);
                done.Add(a);
                order.Add(a);
            }
            foreach (string a in assemblies) Visit(a);
            File.WriteAllLines(Path.Combine(outDir, "build-order.txt"), order);
        }

        private string BuildProject(string asm, string absOverlay)
        {
            StringBuilder p = new StringBuilder();
            p.AppendLine("<Project Sdk=\"Microsoft.NET.Sdk\">");
            p.AppendLine("  <!-- Generated by RefStubGen. Compile-only reference stub. -->");
            p.AppendLine("  <PropertyGroup>");
            p.AppendLine("    <TargetFramework>net35</TargetFramework>");
            p.AppendLine($"    <AssemblyName>{asm}</AssemblyName>");
            p.AppendLine("    <RootNamespace>Stub</RootNamespace>");
            p.AppendLine("    <LangVersion>9.0</LangVersion>");
            p.AppendLine("    <Nullable>disable</Nullable>");
            p.AppendLine("    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>");
            p.AppendLine("    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>");
            p.AppendLine("    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>");
            p.AppendLine("    <TreatWarningsAsErrors>false</TreatWarningsAsErrors>");
            p.AppendLine("    <NoWarn>$(NoWarn);CS0108;CS0109;CS0114;CS0618;CS0660;CS0661;CS0067;CS0649;CS0169;CS0626;CS0824;CS1591</NoWarn>");
            p.AppendLine("    <OutputPath>..\\bin\\</OutputPath>");
            p.AppendLine("    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>");
            p.AppendLine("    <ProduceReferenceAssembly>false</ProduceReferenceAssembly>");
            p.AppendLine("    <DebugType>none</DebugType>");
            p.AppendLine("  </PropertyGroup>");
            p.AppendLine("  <ItemGroup>");
            p.AppendLine("    <PackageReference Include=\"Microsoft.NETFramework.ReferenceAssemblies.net35\" Version=\"1.0.3\" PrivateAssets=\"all\" />");
            p.AppendLine($"    <Compile Include=\"{asm}.g.cs\" />");
            if (absOverlay != null)
            {
                string ov = Path.Combine(absOverlay, asm + ".cs");
                p.AppendLine($"    <Compile Include=\"{ov}\" Condition=\"Exists('{ov}')\" />");
            }
            if (dependencies.TryGetValue(asm, out HashSet<string> deps))
            {
                foreach (string d in deps.Where(targets.Contains).OrderBy(x => x, StringComparer.Ordinal))
                    p.AppendLine($"    <ProjectReference Include=\"..\\{d}\\{d}.csproj\" Private=\"false\" />");
            }
            p.AppendLine("  </ItemGroup>");
            p.AppendLine("</Project>");
            return p.ToString();
        }

