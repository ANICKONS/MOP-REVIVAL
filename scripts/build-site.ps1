<#
    Builds the compatibility website (site/) from compat/mods.json and the built-in rule files (src/MOPR/Rules).

    Writes site/data/mods.js (the data the page reads) and copies the mod icon. Both are generated: they are not
    committed. Fails when the data is inconsistent, so a rule file can't ship without its entry on the site:
      * every built-in rule file needs an entry in compat/mods.json (same ID);
      * IDs are unique; status is works | fix | partial | incompatible | untested; dates are yyyy-MM-dd;
      * "fix" needs rules that do something or "code": true (an empty rule file is not a fix).

    Used locally (preview: open site/index.html) and by .github/workflows/site.yml (GitHub Pages).
#>
[CmdletBinding()]
param(
    [string]$OutDir = ''
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
if (-not $OutDir) { $OutDir = Join-Path $Root 'site' }

$errors = New-Object System.Collections.Generic.List[string]

# --- Built-in rules: comments are allowed in the files (// lines), the JSON itself is standard. ----------------
$rules = @{}
foreach ($f in Get-ChildItem (Join-Path $Root 'src/MOPR/Rules') -Filter '*.json') {
    $text = [IO.File]::ReadAllText($f.FullName, [Text.Encoding]::UTF8)
    $json = ($text -split "`n" | Where-Object { $_ -notmatch '^\s*//' }) -join "`n"
    try { $parsed = $json | ConvertFrom-Json }
    catch { $errors.Add("$($f.Name): not valid JSON ($($_.Exception.Message))"); continue }
    $body = [ordered]@{}
    foreach ($p in $parsed.PSObject.Properties) {
        if ($p.Name -in 'mod', 'replaceBundled') { continue }
        $body[$p.Name] = $p.Value
    }
    $rules[$f.BaseName] = $body
}

# --- The list. ------------------------------------------------------------------------------------------------
$listPath = Join-Path $Root 'compat/mods.json'
$list = [IO.File]::ReadAllText($listPath, [Text.Encoding]::UTF8) | ConvertFrom-Json
$statuses = 'works', 'fix', 'partial', 'incompatible', 'untested'
$seen = @{}
$mods = New-Object System.Collections.Generic.List[object]
foreach ($m in $list.mods) {
    if (-not $m.id) { $errors.Add('compat/mods.json: an entry without "id"'); continue }
    if ($seen.ContainsKey($m.id)) { $errors.Add("compat/mods.json: $($m.id) is listed twice"); continue }
    $seen[$m.id] = $true
    if ($statuses -notcontains $m.status) { $errors.Add("compat/mods.json: $($m.id): status must be one of $($statuses -join ', ')") }
    if ($m.tested -and $m.tested -notmatch '^\d{4}-\d{2}-\d{2}$') { $errors.Add("compat/mods.json: $($m.id): tested must be yyyy-MM-dd") }

    $entry = [ordered]@{
        id      = $m.id
        name    = if ($m.name) { $m.name } else { $m.id -replace '_', ' ' }
        author  = $m.author
        url     = $m.url
        aliases = @($m.aliases | Where-Object { $_ })
        status  = $m.status
        origin  = $m.origin
        code    = [bool]$m.code
        since   = if ($m.since) { $m.since } elseif ($m.origin -eq 'mop') { '5.0.0' } else { $null }
        tested  = $m.tested
        notes   = $m.notes
        rules   = if ($rules.ContainsKey($m.id) -and $rules[$m.id].Count -gt 0) { $rules[$m.id] } else { $null }
    }
    if ($m.status -eq 'fix' -and -not $entry.rules -and -not $entry.code) {
        $errors.Add("compat/mods.json: $($m.id): status ""fix"" needs a rule file (src/MOPR/Rules/$($m.id).json) or ""code"": true")
    }
    $mods.Add($entry)
}
foreach ($id in $rules.Keys) {
    if (-not $seen.ContainsKey($id)) { $errors.Add("src/MOPR/Rules/$id.json has no entry in compat/mods.json") }
}

if ($errors.Count -gt 0) {
    $errors | ForEach-Object { Write-Host "[site] $_" -ForegroundColor Red }
    exit 1
}

# --- Version of the mod (BuildInfo.Version). ------------------------------------------------------------------
$info = [IO.File]::ReadAllText((Join-Path $Root 'src/MOPR/Properties/AssemblyInfo.cs'))
$version = [regex]::Match($info, 'const string Version = "([^"]+)"').Groups[1].Value

$data = [ordered]@{
    version   = $version
    generated = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd')
    mods      = ($mods | Sort-Object { $_.name.ToLowerInvariant() })
}
$js = "// Generated by scripts/build-site.ps1 from compat/mods.json and src/MOPR/Rules. Do not edit.`n" +
      "window.MOPR_COMPAT = " + ($data | ConvertTo-Json -Depth 12 -Compress) + ";`n"

New-Item -ItemType Directory -Force -Path (Join-Path $OutDir 'data') | Out-Null
[IO.File]::WriteAllText((Join-Path $OutDir 'data/mods.js'), $js, (New-Object Text.UTF8Encoding($false)))
Copy-Item (Join-Path $Root 'docs/images/icon.png') (Join-Path $OutDir 'icon.png') -Force

$byStatus = $mods | Group-Object { $_.status } | ForEach-Object { "$($_.Name) $($_.Count)" }
Write-Host "[site] $($mods.Count) mods ($($byStatus -join ', ')), MOPR $version -> $OutDir" -ForegroundColor Green
